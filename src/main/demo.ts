/**
 * A library you can actually open.
 *
 * Lectern is hard to understand from a screenshot: the point is a pile of papers,
 * a manuscript that cites them, and Claude Code pointed at the same folder. So
 * ship a small working example of exactly that — `lectern --demo <folder>`, or
 * `npm run example` to regenerate the copy committed under `examples/library`.
 *
 * It is built by calling the SAME functions the app calls (`addLibraryPapers`,
 * `createProject`, `updateLibraryPaper`, …) rather than by committing a
 * hand-written `library.json`. The previous checked-in example rotted precisely
 * because it was hand-written: it still used `.sources/` and `.lectern/` long
 * after the code moved to `sources/` and `.lctrn/`, and its PDFs were zero bytes.
 * Generating it means the example cannot describe a layout the code doesn't
 * produce.
 *
 * The papers are FICTIONAL — synthesised here with pdf-lib rather than shipped
 * as real PDFs, which keeps the repo free of redistribution questions and
 * guarantees a text layer for search and citekey extraction. They are written to
 * look like the accounting/sustainability literature the app was built for. The
 * DOIs are deliberately absent so nothing here invites a Crossref lookup for a
 * paper that does not exist.
 */

