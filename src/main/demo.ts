/** Render one demo paper to a PDF with a genuine, searchable text layer. */
async function writePdf(path: string, paper: DemoPaper): Promise<void> {
  const doc = await PDFDocument.create()
  const body = await doc.embedFont(StandardFonts.TimesRoman)
  const bold = await doc.embedFont(StandardFonts.TimesRomanBold)
  const italic = await doc.embedFont(StandardFonts.TimesRomanItalic)

  const W = 595.28 // A4
  const H = 841.89
  const M = 72
  const width = W - M * 2

  let page = doc.addPage([W, H])
  let y = H - M

  const wrap = (text: string, font: typeof body, size: number): string[] => {
    const lines: string[] = []
    let line = ''
    for (const word of text.split(/\s+/)) {
      const next = line ? `${line} ${word}` : word
      if (font.widthOfTextAtSize(next, size) > width && line) {
        lines.push(line)
        line = word
      } else {
        line = next
      }
    }
    if (line) lines.push(line)
    return lines
  }

  const draw = (
    text: string,
    { font = body, size = 10.5, gap = 4, color = rgb(0.1, 0.1, 0.12) } = {}
  ): void => {
    for (const line of wrap(text, font, size)) {
      if (y < M + size) {
        page = doc.addPage([W, H])
        y = H - M
      }
      page.drawText(line, { x: M, y, size, font, color })
      y -= size * 1.35
    }
    y -= gap
  }

  draw(paper.patch.title ?? '', { font: bold, size: 16, gap: 10 })
  draw((paper.patch.authors ?? []).join(' · '), { font: italic, size: 11, gap: 2 })
  draw(AFFILIATION, { font: italic, size: 9, gap: 14, color: rgb(0.45, 0.45, 0.5) })
  draw(
    `${paper.patch.journal}, ${paper.patch.year}, ${paper.patch.volume}(${paper.patch.issue}), ${paper.patch.pages}`,
    { font: italic, size: 9.5, gap: 16, color: rgb(0.35, 0.35, 0.4) }
  )
  draw('Abstract', { font: bold, size: 11, gap: 4 })
  draw(paper.patch.abstract ?? '', { size: 10, gap: 18 })

  for (const section of paper.sections) {
    draw(section.heading, { font: bold, size: 12, gap: 5 })
    for (const p of section.paragraphs) draw(p, { gap: 9 })
    y -= 4
  }

  await fs.writeFile(path, await doc.save())
}

/**
 * Build a self-contained example library at `root`. Safe to point at an existing
 * folder: every step underneath is additive, so re-running tops it up rather
 * than destroying work.
 */
export async function createDemoLibrary(root: string): Promise<{ root: string; projectPath: string }> {
  await fs.mkdir(root, { recursive: true })

  // The PDFs are written to a scratch folder and imported through the real
  // importer, so they land in `sources/` under whatever naming and registry
  // rules the app currently applies.
  const staging = await fs.mkdtemp(join(tmpdir(), 'lectern-demo-'))
  try {
    const paths: string[] = []
    for (const paper of PAPERS) {
      const path = join(staging, paper.file)
      await writePdf(path, paper)
      paths.push(path)
    }

    const added = await addLibraryPapers(root, paths)
    for (let i = 0; i < PAPERS.length; i++) {
      const entry = added[i]
      if (!entry) continue
      // Fill in the metadata a real import would have got from Crossref or the
      // PDF itself...
      await updateLibraryPaper(root, entry.id, PAPERS[i].patch)
      // ...then let the app name the file, rather than trusting the name I
      // guessed above. Otherwise the first person to open the example would
      // watch all three PDFs rename themselves, which looks like a bug.
      await renamePaperToHouseStyle(root, entry.id)
    }

    const created = await createProject(
      root,
      'carbon-disclosure-review',
      {
        title: 'Does mandatory carbon disclosure inform investors?',
        authors: ['Your Name'],
        manuscriptFile: 'manuscript.qmd'
      },
      new Date().toISOString()
    )
    if (!created.ok || !created.projectPath) {
      throw new Error(created.error || 'could not scaffold the demo project')
    }

    // Foreground the two papers the manuscript actually cites; the third stays
    // in the pile, which is the normal state of a library.
    for (const citekey of ['ingram2024', 'vasquez2023']) {
      const paper = added.find((_, i) => PAPERS[i].patch.citekey === citekey)
      if (paper) await addProjectPaper(root, created.projectPath, paper.id)
    }

    await saveDoc(created.projectPath, MANUSCRIPT)
    return { root, projectPath: created.projectPath }
  } finally {
    await fs.rm(staging, { recursive: true, force: true }).catch(() => {})
  }
}
